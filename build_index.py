#!/usr/bin/env python3
"""Regenerate research-data.js from notes/*.md frontmatter.
Usage: python build_index.py   (run from the site folder)
Frontmatter keys: title, summary, topic, tags, date (YYYY-MM-DD), status, url
Add `publish: false` to a note to keep it off the site.
"""
import json, re, pathlib
root = pathlib.Path(__file__).parent
out = []
for f in sorted((root / "notes").glob("*.md")):
    text = f.read_text(encoding="utf-8")
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n", text, re.S)
    meta, key = {}, None
    for line in (m.group(1).splitlines() if m else []):
        if re.match(r"^\s+-\s+", line) and key:            # YAML list item
            meta.setdefault(key, []).append(line.split("-", 1)[1].strip().strip("\"'"))
        elif ":" in line:
            key, val = [p.strip() for p in line.split(":", 1)]
            if val.startswith("["):
                meta[key] = [t.strip().strip("\"'") for t in val.strip("[]").split(",") if t.strip()]
            elif val:
                meta[key] = val.strip("\"'")
    if str(meta.get("publish", "true")).lower() == "false":
        continue
    out.append({"slug": f.stem, "title": meta.get("title", f.stem.replace("-", " ").title()),
                "summary": meta.get("summary", ""), "topic": meta.get("topic", "General"),
                "tags": meta.get("tags", []), "date": str(meta.get("date", "")),
                "status": meta.get("status", ""), **({"url": meta["url"]} if "url" in meta else {})})
(root / "research-data.js").write_text(
    "/* Generated by build_index.py */\nwindow.RESEARCH=" + json.dumps(out, indent=1) + ";\n", encoding="utf-8")
print(f"Wrote {len(out)} entries")
